/**
 * Return the bitfield of properties for the given unicode codepoint.
 */
static uint8_t
pm_unicode_codepoint_properties(pm_unicode_codepoint_t codepoint) {
    if (codepoint >= UNICODE_CODEPOINTS_MAXIMUM) return 0;

    uint8_t middle = pm_unicode_root[codepoint >> 8];
    uint8_t leaf = pm_unicode_middle[middle][(codepoint >> 3) & 0x1F];
    return pm_unicode_leaf[leaf][codepoint & 0x7];
}

