#!/usr/bin/env ruby
# frozen_string_literal: true

# Generates float_conv_table.h, the table of powers of 10 used by
# float_conv.c.
#
#   ruby tool/mk_float_conv_table.rb > float_conv_table.h

MASK64 = (1 << 64) - 1

def entry(n)
  raise "not 128 bits: #{n}" unless n.bit_length == 128
  "    {UINT64_C(0x%016x), UINT64_C(0x%016x)}," % [n >> 64, n & MASK64]
end

# 10**k == g * 2**(floor(log2(10**k)) - 127), where g is rounded up to
# 128 bits, as the table in schubfach_64.cc of Drachennest.
def pow10_ceil(k)
  if k >= 0
    n = 10**k
    e = n.bit_length - 1 - 127
    e >= 0 ? (n + (1 << e) - 1) >> e : n << -e
  else
    d = 10**-k
    -((-1 << (d.bit_length + 127)) / d)
  end
end

POW10_MIN = -292
POW10_MAX = 324

# the approximations of logarithms used with the tables must be exact
(POW10_MIN..POW10_MAX).each do |k|
  exact = k >= 0 ? (10**k).bit_length - 1 : -(10**-k).bit_length
  raise "floor(log2(10**#{k}))" unless (k * 1741647) >> 19 == exact
end

puts <<EOS
/* -*- C -*- generated by tool/mk_float_conv_table.rb; do not edit. */

#define FLOAT_CONV_POW10_MIN (#{POW10_MIN})
#define FLOAT_CONV_POW10_MAX #{POW10_MAX}

/*
 * 10**k for FLOAT_CONV_POW10_MIN <= k <= FLOAT_CONV_POW10_MAX, as the
 * high and low halves of g where 10**k == g * 2**(floor(log2(10**k)) -
 * 127) and g is rounded up to 128 bits.
 */
static const uint64_t float_conv_pow10[][2] = {
EOS
(POW10_MIN..POW10_MAX).each {|k| puts entry(pow10_ceil(k))}
puts "};"
